SELECT
SALES_DATE, PRODUCT_ID, USER_ID, SALES_AMOUNT
FROM ONLINE_SALE
WHERE SALES_DATE >='2022-03-01' AND SALES_DATE <= '2022-03-31'
UNION
SELECT
SALES_DATE, PRODUCT_ID, NULL, SALES_AMOUNT
FROM OFFLINE_SALE
WHERE SALES_DATE >='2022-03-01' AND SALES_DATE <= '2022-03-31'

ORDER BY 1, 2, 3;